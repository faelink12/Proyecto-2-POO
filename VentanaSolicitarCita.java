    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        if (listaClientes == null || listaClientes.isEmpty() || jComboBoxCliente.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "Debe registrar y seleccionar un cliente antes de crear la cita.");
            return;
        }

        int index = jComboBoxCliente.getSelectedIndex();
        Clientes clienteSeleccionado = listaClientes.get(index);
        String idCita = jTxtFieldID.getText().trim();
        String idCliente = clienteSeleccionado.getID();
        String fecha = LocalDate.now().format(DateTimeFormatter.ofPattern("dd-MM-yyyy"));
        String obs = jTextAreaObservaciones.getText().trim();

        Citas nuevaCita = new Citas(idCita, idCliente, fecha, obs);

        ArrayList<Citas> citas = ArchivoDat.cargarCitas();
        citas.add(nuevaCita);
        ArchivoDat.guardarCitas(citas);

        JOptionPane.showMessageDialog(
            this,
            "Su solicitud ha sido ingresada exitosamente, Numero " + idCita,
            "# Cita",
            JOptionPane.INFORMATION_MESSAGE
        );

        dispose();
    }//GEN-LAST:event_jButtonSalvarActionPerformed


    public void cargarClientesEnCombo() {
        listaClientes = ArchivoDat.cargarClientes();
        jComboBoxCliente.removeAllItems();
        if (listaClientes.isEmpty()) {
            jComboBoxCliente.addItem("-- Sin clientes registrados --");
        } else {
            for (int i = 0; i < listaClientes.size(); i++) {
                Clientes c = listaClientes.get(i);
                jComboBoxCliente.addItem(c.getID() + " - " + c.getNombre() + " (" + c.getPropietario() + ")");
            }
        }
    }

    private void generarSiguienteID() {
        ArrayList<Citas> citas = ArchivoDat.cargarCitas();
        int maxId = 99;
        for (int i = 0; i < citas.size(); i++) {
            try {
                int idNum = Integer.parseInt(citas.get(i).getID().trim());
                if (idNum > maxId) {
                    maxId = idNum;
                }
            } catch (NumberFormatException ignored) {
            }
        }
        jTxtFieldID.setText(String.valueOf(maxId + 1));
    }


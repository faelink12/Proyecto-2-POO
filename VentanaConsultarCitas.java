    private void consultarCitas() {
        String fNombre = jTxtFieldNombre.getText().trim().toLowerCase();
        String fTel = jTxtFieldTelefono.getText().trim().toLowerCase();
        String fPropietario = jTxtFieldPropietario.getText().trim().toLowerCase();
        String fEmail = jTxtFieldEmail.getText().trim().toLowerCase();

        ArrayList<Citas> citas = ArchivoDat.cargarCitas();
        ArrayList<Clientes> clientes = ArchivoDat.cargarClientes();

        HashMap<String, Clientes> mapaClientes = new HashMap<>();
        for (int i = 0; i < clientes.size(); i++) {
            Clientes c = clientes.get(i);
            mapaClientes.put(c.getID(), c);
        }

        DefaultTableModel modelo = new DefaultTableModel(
            new Object[][]{},
            new String[]{"ID", "Nombre", "Fecha"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (int i = 0; i < citas.size(); i++) {
            Citas cita = citas.get(i);
            Clientes cliente = mapaClientes.get(cita.getIdCliente());

            String nomCliente = cliente != null ? cliente.getNombre() : "Desconocido";
            String telCliente = cliente != null ? cliente.getTelefono() : "";
            String propCliente = cliente != null ? cliente.getPropietario() : "";
            String emailCliente = cliente != null ? cliente.getEmail() : "";

            boolean coincide = true;
            if (!fNombre.isEmpty() && !nomCliente.toLowerCase().contains(fNombre)) {
                coincide = false;
            }
            if (!fTel.isEmpty() && !telCliente.toLowerCase().contains(fTel)) {
                coincide = false;
            }
            if (!fPropietario.isEmpty() && !propCliente.toLowerCase().contains(fPropietario)) {
                coincide = false;
            }
            if (!fEmail.isEmpty() && !emailCliente.toLowerCase().contains(fEmail)) {
                coincide = false;
            }

            if (coincide) {
                modelo.addRow(new Object[]{
                    cita.getId(),
                    nomCliente,
                    cita.getFecha()
                });
            }
        }

        jTableCitas.setModel(modelo);
    }


    private void jButtonCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCrearActionPerformed
    
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPrecio.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        ArrayList<Servicios> servicios = ArchivoDat.cargarServicios();

        for (int i = 0; i < servicios.size(); i++) {
            if (servicios.get(i).getID().equals(jTxtFieldID.getText().trim())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un servicio con ese ID.");
                return;
            }
        }


        double precio;
        try {
            precio = Double.parseDouble(jTxtFieldPrecio.getText());
            if (precio < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "El precio no puede ser negativo.");
                return;
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un precio válido.");
            return;
        }

        Servicios servicio = new Servicios(
            jTxtFieldID.getText().trim(),
            jTxtFieldNombre.getText().trim(),
            precio
        );

        servicios.add(servicio);

        ArchivoDat.guardarServicios(servicios);

        cargarServicios();

    }//GEN-LAST:event_jButtonCrearActionPerformed

    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
    
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPrecio.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        int fila = jTable2.getSelectedRow();
    
        if (fila >= 0) {

            ArrayList<Servicios> servicios = ArchivoDat.cargarServicios();

            Servicios servicio = servicios.get(fila);

            double precio;
            try {
                precio = Double.parseDouble(jTxtFieldPrecio.getText());
                if (precio < 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "El precio no puede ser negativo.");
                    return;
                }
            } catch (NumberFormatException ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un precio válido.");
                return;
            }

            servicio.setID(jTxtFieldID.getText().trim());
            servicio.setNombre(jTxtFieldNombre.getText().trim());
            servicio.setPrecio(precio);

            ArchivoDat.guardarServicios(servicios);

            cargarServicios();
        }
    
    }//GEN-LAST:event_jButtonActualizarActionPerformed

    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
    
        int fila = jTable2.getSelectedRow();
    
        if (fila >= 0) {

            ArrayList<Servicios> servicios = ArchivoDat.cargarServicios();
            servicios.remove(fila);

            ArchivoDat.guardarServicios(servicios);

            cargarServicios();
        }
    
    }//GEN-LAST:event_jButtonEliminarActionPerformed

    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
    
        int fila = jTable2.getSelectedRow();

        if (fila >= 0) {

            jTxtFieldID.setText(jTable2.getValueAt(fila, 0).toString());

            jTxtFieldNombre.setText(jTable2.getValueAt(fila, 1).toString());

            jTxtFieldPrecio.setText(jTable2.getValueAt(fila, 2).toString());
        }
    
    }//GEN-LAST:event_jTable2MouseClicked


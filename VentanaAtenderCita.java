    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        int idx = jComboBoxCitas.getSelectedIndex();
        if (idx < 0 || idx >= listaCitas.size()) {
            JOptionPane.showMessageDialog(this, "Seleccione una cita válida.");
            return;
        }

        int vetIdx = jComboBoxVeterinarios.getSelectedIndex();
        if (vetIdx <= 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un veterinario para atender la cita.");
            return;
        }

        Veterinarios vetSeleccionado = listaVeterinarios.get(vetIdx - 1);
        Citas cita = listaCitas.get(idx);

        cita.setIdVet(vetSeleccionado.getID());
        cita.setObservaciones(jTextAreaObservaciones.getText().trim());

        ArrayList<String> diags = new ArrayList<>();
        for (int i = 0; i < modeloDiagnosticos.getRowCount(); i++) {
            diags.add(modeloDiagnosticos.getValueAt(i, 0).toString());
        }
        cita.setDiagnosticos(diags);

        ArrayList<String> trats = new ArrayList<>();
        for (int i = 0; i < modeloTratamientos.getRowCount(); i++) {
            trats.add(modeloTratamientos.getValueAt(i, 0).toString());
        }
        cita.setTratamientos(trats);

        ArchivoDat.guardarCitas(listaCitas);

        JOptionPane.showMessageDialog(this, "Cita atendida y guardada exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }//GEN-LAST:event_jButtonSalvarActionPerformed


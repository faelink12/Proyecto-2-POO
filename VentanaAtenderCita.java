    private void cargarDatosIniciales() {
        listaCitas = ArchivoDat.cargarCitas();
        listaVeterinarios = ArchivoDat.cargarVeterinarios();
        ArrayList<Clientes> clientes = ArchivoDat.cargarClientes();

        mapaClientes = new HashMap<>();
        for (int i = 0; i < clientes.size(); i++) {
            Clientes c = clientes.get(i);
            mapaClientes.put(c.getID(), c);
        }

        jComboBoxCitas.removeAllItems();
        if (listaCitas.isEmpty()) {
            jComboBoxCitas.addItem("-- Sin citas registradas --");
        } else {
            for (int i = 0; i < listaCitas.size(); i++) {
                jComboBoxCitas.addItem(listaCitas.get(i).getId());
            }
        }

        jComboBoxVeterinarios.removeAllItems();
        jComboBoxVeterinarios.addItem("-- Seleccione Veterinario --");
        for (int i = 0; i < listaVeterinarios.size(); i++) {
            Veterinarios v = listaVeterinarios.get(i);
            jComboBoxVeterinarios.addItem(v.getID() + " - " + v.getNombre());
        }

        if (!listaCitas.isEmpty()) {
            seleccionarCita(0);
        }
    }

    private void seleccionarCita(int index) {
        if (index < 0 || index >= listaCitas.size()) {
            return;
        }

        Citas cita = listaCitas.get(index);

        Clientes c = mapaClientes.get(cita.getIdCliente());
        jTxtFieldIdCliente.setText(cita.getIdCliente());
        jTxtFieldNomCliente.setText(c != null ? c.getNombre() : "No registrado");

        String idVet = cita.getIdVet();
        int vetIdx = 0;
        if (idVet != null && !idVet.trim().isEmpty()) {
            for (int i = 0; i < listaVeterinarios.size(); i++) {
                if (listaVeterinarios.get(i).getID().equalsIgnoreCase(idVet.trim())) {
                    vetIdx = i + 1;
                    break;
                }
            }
        }
        jComboBoxVeterinarios.setSelectedIndex(vetIdx);

        jTextAreaObservaciones.setText(cita.getObservaciones());

        modeloDiagnosticos = new DefaultTableModel(new Object[][]{}, new String[]{"Diagnostico"}) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        ArrayList<String> diags = cita.getDiagnosticos();
        if (diags != null) {
            for (int i = 0; i < diags.size(); i++) {
                modeloDiagnosticos.addRow(new Object[]{diags.get(i)});
            }
        }
        jTableDiagnosticos.setModel(modeloDiagnosticos);

        modeloTratamientos = new DefaultTableModel(new Object[][]{}, new String[]{"Tratamiento"}) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        ArrayList<String> trats = cita.getTratamientos();
        if (trats != null) {
            for (int i = 0; i < trats.size(); i++) {
                modeloTratamientos.addRow(new Object[]{trats.get(i)});
            }
        }
        jTableTratamientos.setModel(modeloTratamientos);
    }


    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPropietario.getText().trim().isEmpty() || jTxtFieldTel.getText().trim().isEmpty() || jTxtFieldCorreo.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        int fila = jTable1.getSelectedRow();

        if (fila >= 0) {

            ArrayList<Clientes> clientes = ArchivoDat.cargarClientes();

            Clientes cliente = clientes.get(fila);

            cliente.setID(jTxtFieldID.getText());

            cliente.setNombre(jTxtFieldNombre.getText());

            cliente.setPropietario(jTxtFieldPropietario.getText());

            cliente.setTelefono(jTxtFieldTel.getText());

            cliente.setEmail(jTxtFieldCorreo.getText());


            ArchivoDat.guardarClientes(clientes);

            cargarClientes();

        }
    }//GEN-LAST:event_jButtonActualizarActionPerformed

    private void jButtonCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCrearActionPerformed
        
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPropietario.getText().trim().isEmpty() || jTxtFieldTel.getText().trim().isEmpty() || jTxtFieldCorreo.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        ArrayList<Clientes> clientes = ArchivoDat.cargarClientes();
        for (int i = 0; i < clientes.size(); i++) {
            if (clientes.get(i).getID().equals(jTxtFieldID.getText().trim())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un cliente con ese ID.");
                return;
            }
        }

        Clientes cliente = new Clientes(jTxtFieldID.getText().trim(), jTxtFieldNombre.getText().trim(), jTxtFieldPropietario.getText().trim(), jTxtFieldTel.getText().trim(), jTxtFieldCorreo.getText().trim());

        clientes.add(cliente);

        ArchivoDat.guardarClientes(clientes);

        cargarClientes();
        
    }//GEN-LAST:event_jButtonCrearActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        
        int fila = jTable1.getSelectedRow();

        if (fila >= 0) {

            jTxtFieldID.setText(jTable1.getValueAt(fila, 0).toString());

            jTxtFieldNombre.setText(jTable1.getValueAt(fila, 1).toString());

            jTxtFieldPropietario.setText(jTable1.getValueAt(fila, 2).toString());

            jTxtFieldTel.setText(jTable1.getValueAt(fila, 3).toString());

            jTxtFieldCorreo.setText(jTable1.getValueAt(fila, 4).toString());

        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
        
        int fila = jTable1.getSelectedRow();

        if (fila >= 0) {

            ArrayList<Clientes> clientes = ArchivoDat.cargarClientes();

            clientes.remove(fila);

            ArchivoDat.guardarClientes(clientes);

            cargarClientes();

        }
    }//GEN-LAST:event_jButtonEliminarActionPerformed


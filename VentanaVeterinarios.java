    private void jButtonCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCrearActionPerformed
        
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPuesto.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        ArrayList<Veterinarios> veterinarios = ArchivoDat.cargarVeterinarios();
        for (int i = 0; i < veterinarios.size(); i++) {
            if (veterinarios.get(i).getID().equals(jTxtFieldID.getText().trim())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un veterinario con ese ID.");
                return;
            }
        }

        Veterinarios veterinario = new Veterinarios(jTxtFieldID.getText().trim(), jTxtFieldNombre.getText().trim(), jTxtFieldPuesto.getText().trim());

        veterinarios.add(veterinario);

        ArchivoDat.guardarVeterinarios(veterinarios);

        cargarVeterinarios();
        
    }//GEN-LAST:event_jButtonCrearActionPerformed

    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        
        if (jTxtFieldID.getText().trim().isEmpty() || jTxtFieldNombre.getText().trim().isEmpty() || jTxtFieldPuesto.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        int fila = jTable1.getSelectedRow();

        if (fila >= 0) {

            ArrayList<Veterinarios> veterinarios = ArchivoDat.cargarVeterinarios();

            Veterinarios veterinario = veterinarios.get(fila);

            veterinario.setID(jTxtFieldID.getText());

            veterinario.setNombre(jTxtFieldNombre.getText());

            veterinario.setPuesto(jTxtFieldPuesto.getText());

            ArchivoDat.guardarVeterinarios(veterinarios);

            cargarVeterinarios();

        }

    }//GEN-LAST:event_jButtonActualizarActionPerformed

